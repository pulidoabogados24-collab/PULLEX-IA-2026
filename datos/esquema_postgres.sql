-- PULLEX IA — esquema de la base principal en PostgreSQL (Supabase)
-- version: 1
--
-- Qué es: las tablas de la base principal (cuentas, conversaciones, Academia, documentos, taller, perfiles y
-- telemetría), con los mismos nombres y columnas que crea la app en SQLite. tests/test_esquema_bd.py compara
-- los dos esquemas: si agregas una columna en un lado y no en el otro, esa prueba falla.
--
-- Cómo se aplica: el archivo NO nombra el esquema. Se ejecuta con el search_path puesto, dentro de una
-- transacción:
--     BEGIN;
--     SET LOCAL search_path TO pullex;
--     \i datos/esquema_postgres.sql      -- o pegar aquí el contenido
--     COMMIT;
-- La app también lo aplica sola al arrancar si la tabla esquema_version no existe o tiene una versión menor
-- que la de la línea «-- version:» de arriba (datos.asegurar_esquema). Es idempotente: aplicarlo dos veces
-- no cambia nada ni borra datos.
--
-- Tipos: INTEGER de SQLite → BIGINT; REAL → DOUBLE PRECISION (las fechas son segundos desde 1970, como en
-- SQLite); BLOB → BYTEA; «INTEGER PRIMARY KEY AUTOINCREMENT» → identidad. Los textos llevan COLLATE "C" para
-- que comparar y ordenar dé lo mismo que en SQLite (byte a byte), sin depender del idioma de la base.
--
-- Seguridad: todas las tablas quedan con seguridad por filas activada y SIN políticas. El dueño de las tablas
-- (el usuario con que se conecta la app) las sigue usando; cualquier otro rol no ve ninguna fila. Lo propio
-- de Supabase (roles anon y authenticated) está en datos/supabase_seguridad.sql.
--
-- Para cambiar el esquema: (1) cambia la tabla en SQLite (app.py o el módulo dueño de la tabla), (2) agrega
-- abajo, en «Cambios posteriores», un ALTER TABLE ... ADD COLUMN IF NOT EXISTS ... (y la columna en su
-- CREATE TABLE), (3) sube el número de «-- version:» y agrega su fila al final. Nunca borres ni renombres
-- columnas aquí sin un plan de migración de datos.

-- El esquema de destino es el primero del search_path. Se niega a instalarse en «public» o sin search_path
-- propio: esta base se comparte con otros productos.
DO $pullex$
DECLARE
    ruta text := current_setting('search_path');
    destino text := btrim(split_part(ruta, ',', 1), ' "');
BEGIN
    IF destino = '' OR destino IN ('public', '$user', 'information_schema') OR left(destino, 3) = 'pg_' THEN
        RAISE EXCEPTION 'PULLEX IA: antes de aplicar este archivo fija el esquema de destino (SET LOCAL search_path TO pullex). search_path actual: %', ruta;
    END IF;
    IF to_regnamespace(quote_ident(destino)) IS NULL THEN
        EXECUTE format('CREATE SCHEMA IF NOT EXISTS %I', destino);
    END IF;
END
$pullex$;

CREATE TABLE IF NOT EXISTS esquema_version (
    version BIGINT PRIMARY KEY,
    aplicada DOUBLE PRECISION NOT NULL,
    nota TEXT COLLATE "C"
);

-- ---- Cuentas y sesiones (app.py) ----
CREATE TABLE IF NOT EXISTS usuarios (
    email TEXT COLLATE "C" PRIMARY KEY,
    nombre TEXT COLLATE "C",
    sal TEXT COLLATE "C",
    hash TEXT COLLATE "C",
    plan TEXT COLLATE "C" DEFAULT 'prueba',
    limite BIGINT DEFAULT 10,
    usadas BIGINT DEFAULT 0,
    periodo TEXT COLLATE "C",
    activo BIGINT DEFAULT 1,
    es_admin BIGINT DEFAULT 0,
    email_verificado BIGINT DEFAULT 0,
    preferencias TEXT COLLATE "C" DEFAULT '{}',
    creado DOUBLE PRECISION,
    sesion_version BIGINT DEFAULT 0,
    acepto_politica_version TEXT COLLATE "C",
    acepto_politica_en DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS tokens_accion (
    token TEXT COLLATE "C" PRIMARY KEY,
    email TEXT COLLATE "C" NOT NULL,
    tipo TEXT COLLATE "C" NOT NULL,
    creado DOUBLE PRECISION NOT NULL,
    expira DOUBLE PRECISION NOT NULL,
    usado BIGINT DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_tokens_email ON tokens_accion (email, tipo);
-- Límites por cuenta compartidos entre instancias (AUTH-04): clave → inicio del bloque y número de intentos.
CREATE TABLE IF NOT EXISTS limites (
    clave TEXT COLLATE "C" PRIMARY KEY,
    inicio DOUBLE PRECISION NOT NULL,
    n BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS apariencia_imagenes (
    usuario TEXT COLLATE "C" NOT NULL,
    tipo TEXT COLLATE "C" NOT NULL,
    mime TEXT COLLATE "C" NOT NULL,
    data BYTEA NOT NULL,
    actualizado DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (usuario, tipo)
);

